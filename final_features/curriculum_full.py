def seed(db_path=schema.DB_PATH):
    schema.initialize(db_path); con=sqlite3.connect(db_path); c=con.cursor()
    for subject,data in [('Физика',PHYSICS),('Химия',CHEMISTRY)]:
        for grade,sections in data.items():
            order=0
            for section,topics in sections.items():
                for topic in topics:
                    c.execute('''INSERT OR IGNORE INTO learning_topics(subject,study_goal,grade,section,topic,sort_order,formula_key)
                                 VALUES(?,?,?,?,?,?,?)''',(subject,'',grade,section,topic,order,f'{subject}:{grade}:{section}:{topic}'))
                    order+=1
    # Exam paths use the same rich topics but separate goal tags for filtering when needed.
    for goal,grades in [('OGE',[8,9]),('EGE',[10,11])]:
        for subject,data in [('Физика',PHYSICS),('Химия',CHEMISTRY)]:
            order=0
            for grade in grades:
                if grade not in data: continue
                for section,topics in data[grade].items():
                    for topic in topics:
                        c.execute('''INSERT OR IGNORE INTO learning_topics(subject,study_goal,grade,section,topic,sort_order,formula_key)
                                     VALUES(?,?,?,?,?,?,?)''',(subject,goal,grade,section,topic,order,f'{subject}:{grade}:{section}:{topic}'))
                        order+=1
    con.commit(); con.close()
